"""Build transformed tables and the cash-flow reporting mart from raw extracts.

Reads data/raw/*.json, writes data/transformed/*.json and
data/reporting/cashflow-forecast.json. Stdlib only.

Usage (from repo root):
    python scripts/build_report_data.py
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
TRANSFORMED = ROOT / "data" / "transformed"
REPORTING = ROOT / "data" / "reporting"

